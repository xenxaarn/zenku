#!/usr/bin/env bash
# Bootstrap a bare-metal x86_64-elf cross toolchain.
#
# Installs binutils and a C-only GCC into $PREFIX (default ~/.local/cross).
# The kernel does not require libgcc, but target libgcc is built for the
# 32-bit stage3 and for future userland needs.
#
# Usage:
#   scripts/toolchain.sh
#   PREFIX=/opt/cross GCC_VERSION=15.2.0 scripts/toolchain.sh
#   FORCE=1 scripts/toolchain.sh
set -euo pipefail

TARGET=${TARGET:-x86_64-elf}
BINUTILS_VERSION=${BINUTILS_VERSION:-2.45}
GCC_VERSION=${GCC_VERSION:-15.2.0}
PREFIX=${PREFIX:-$HOME/.local/cross}
JOBS=${JOBS:-$(nproc)}
MIRROR=${MIRROR:-https://ftpmirror.gnu.org}

ROOT=$(cd "$(dirname "$0")/.." && pwd)
SRC_DIR="$ROOT/build/toolchain-src"
BUILD_DIR="$ROOT/build/toolchain-build"
DL_DIR="$SRC_DIR/downloads"

log()  { printf '\033[1;34m[toolchain]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[toolchain]\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m[toolchain]\033[0m %s\n' "$*" >&2; exit 1; }

if [ "${FORCE:-0}" != "1" ] &&
   [ -x "$PREFIX/bin/$TARGET-gcc" ] &&
   [ -x "$PREFIX/bin/$TARGET-ld" ]; then
    log "toolchain already installed at $PREFIX"
    log "use FORCE=1 to rebuild"
    exit 0
fi

for tool in curl tar xz make gcc g++ bison flex makeinfo; do
    command -v "$tool" >/dev/null 2>&1 || \
        die "missing host tool '$tool'. On Fedora: sudo dnf install gcc gcc-c++ make bison flex texinfo curl xz"
done

check_header() {
    local header=$1
    local dir
    for dir in /usr/include /usr/local/include /usr/include/x86_64-linux-gnu; do
        [ -f "$dir/$header" ] && return 0
    done
    return 1
}

missing_headers=()
for header in gmp.h mpfr.h mpc.h; do
    check_header "$header" || missing_headers+=("$header")
done
if [ "${#missing_headers[@]}" -ne 0 ]; then
    warn "missing development headers: ${missing_headers[*]}"
    warn "Fedora: sudo dnf install gmp-devel mpfr-devel libmpc-devel"
    warn "Debian: sudo apt install libgmp-dev libmpfr-dev libmpc-dev"
    exit 1
fi

mkdir -p "$DL_DIR" "$BUILD_DIR/binutils" "$BUILD_DIR/gcc" "$PREFIX"

fetch() {
    local url=$1
    local dest=$2
    if [ -f "$dest" ]; then
        log "using cached $(basename "$dest")"
        return 0
    fi
    log "downloading $url"
    curl -fL --retry 3 --connect-timeout 20 -o "$dest.part" "$url"
    mv "$dest.part" "$dest"
}

BINUTILS_TARBALL="$DL_DIR/binutils-$BINUTILS_VERSION.tar.xz"
GCC_TARBALL="$DL_DIR/gcc-$GCC_VERSION.tar.xz"

fetch "$MIRROR/binutils/binutils-$BINUTILS_VERSION.tar.xz" "$BINUTILS_TARBALL"
fetch "$MIRROR/gcc/gcc-$GCC_VERSION/gcc-$GCC_VERSION.tar.xz" "$GCC_TARBALL"

if [ ! -d "$SRC_DIR/binutils-$BINUTILS_VERSION" ]; then
    log "extracting binutils"
    tar -C "$SRC_DIR" -xf "$BINUTILS_TARBALL"
fi
if [ ! -d "$SRC_DIR/gcc-$GCC_VERSION" ]; then
    log "extracting gcc"
    tar -C "$SRC_DIR" -xf "$GCC_TARBALL"
fi

log "configuring binutils $BINUTILS_VERSION"
"$SRC_DIR/binutils-$BINUTILS_VERSION/configure" \
    --target="$TARGET" \
    --prefix="$PREFIX" \
    --disable-nls \
    --disable-werror \
    --disable-multilib \
    --disable-shared \
    --enable-deterministic-archives

log "building binutils (-j$JOBS)"
make -C "$BUILD_DIR/binutils" -j"$JOBS"
make -C "$BUILD_DIR/binutils" install

log "configuring gcc $GCC_VERSION"
"$SRC_DIR/gcc-$GCC_VERSION/configure" \
    --target="$TARGET" \
    --prefix="$PREFIX" \
    --disable-nls \
    --disable-bootstrap \
    --disable-werror \
    --disable-shared \
    --disable-multilib \
    --disable-threads \
    --disable-libssp \
    --disable-libquadmath \
    --disable-libgomp \
    --disable-libatomic \
    --disable-libvtv \
    --disable-libsanitizer \
    --enable-languages=c \
    --without-headers

log "building gcc (-j$JOBS)"
make -C "$BUILD_DIR/gcc" -j"$JOBS" all-gcc all-target-libgcc
make -C "$BUILD_DIR/gcc" install-gcc install-target-libgcc

cat > "$PREFIX/env.sh" <<EOF
# Generated by Zenku scripts/toolchain.sh
export PATH="$PREFIX/bin:\$PATH"
EOF

log "installed: $PREFIX"
"$PREFIX/bin/$TARGET-gcc" --version | head -1
"$PREFIX/bin/$TARGET-ld" --version | head -1
log "activate with: source $PREFIX/env.sh"
